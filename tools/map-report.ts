// v1.2 per-map balance report (D-033): every weekday layout of a biome, and Verder on each, played
// by the plinker and competent bots in Classic, against the plain biome. The quota column is the
// map's quota (the season's plain-hunt quota, run.json) — the score that unlocks Verder.
//
// Usage: npx tsx tools/map-report.ts --biome karoo-autumn [--seeds 64] [--workers N]
//          [--out docs/balance/v1.2-karoo-autumn.md]
import { mkdirSync, writeFileSync } from 'node:fs';
import { availableParallelism } from 'node:os';
import { dirname } from 'node:path';
import { WEEKDAY_IDS } from '../src/content/schemas';
import { mapQuota } from '../src/meta/bonusMaps';
import { runWorker, summarise, type HuntRow, type Job } from './balance-sim';
import type { BotKind } from './bots';
import { loadContent } from './testContent';

function arg(name: string, fallback: string): string {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 ? (process.argv[i + 1] ?? fallback) : fallback;
}

const biome = arg('biome', 'karoo-autumn');
const seeds = Number(arg('seeds', '64'));
const workers = Math.max(1, Number(arg('workers', String(availableParallelism()))));
const out = arg('out', '');
const bots: BotKind[] = ['plinker', 'competent'];
const content = loadContent();
const quota = mapQuota(content, biome);

interface MapCase {
  readonly name: string;
  readonly layout?: string;
  readonly bonus?: string;
}
const maps: MapCase[] = [
  { name: 'plain (no layout)' },
  ...WEEKDAY_IDS.map((l) => ({ name: l, layout: l })),
  ...WEEKDAY_IDS.map((l) => ({ name: `${l} + verder`, layout: l, bonus: 'verder' })),
];

const started = performance.now();
const jobs: { map: MapCase; job: Job }[] = [];
const all = Array.from({ length: seeds }, (_, i) => i + 1);
const chunk = Math.max(8, Math.ceil(seeds / 2));
for (const map of maps)
  for (const bot of bots)
    for (let i = 0; i < all.length; i += chunk)
      jobs.push({
        map,
        job: {
          bot,
          seeds: all.slice(i, i + chunk),
          input: 'pointer',
          mode: 'classic',
          biome,
          layout: map.layout,
          bonus: map.bonus,
        },
      });

const rows = new Map<string, HuntRow[]>();
let next = 0;
await Promise.all(
  Array.from({ length: Math.min(workers, jobs.length) }, async () => {
    while (next < jobs.length) {
      const j = jobs[next++];
      if (j === undefined) break;
      const got = await runWorker(j.job);
      const key = `${j.map.name}|${j.job.bot}`;
      rows.set(key, [...(rows.get(key) ?? []), ...got]);
    }
  }),
);

const pct = (x: number): string => `${Math.round(x * 100)} %`;
const lines = [
  `# v1.2 map balance — ${biome}`,
  '',
  `Classic, pointer, ${seeds} seeds per bot and map. Quota (unlocks Verder): ${quota}. ` +
    `Generated by \`npx tsx tools/map-report.ts --biome ${biome} --seeds ${seeds}\`.`,
  '',
  '| map | plinker p50 | competent mean | competent p50 | Δ competent mean vs plain | competent ≥ quota | plinker ≥ quota | bagged (comp.) | secrets (comp.) |',
  '|---|---|---|---|---|---|---|---|---|',
];
let plainMean = 0;
const json: Record<string, unknown>[] = [];
for (const map of maps) {
  const p = rows.get(`${map.name}|plinker`) ?? [];
  const c = rows.get(`${map.name}|competent`) ?? [];
  const sp = summarise('plinker', p);
  const sc = summarise('competent', c);
  if (map.layout === undefined) plainMean = sc.mean;
  const pass = (r: readonly HuntRow[]): number =>
    r.length === 0 ? 0 : r.filter((x) => x.score >= quota).length / r.length;
  const bagged = c.reduce((a, r) => a + r.bagged, 0) / Math.max(1, c.length);
  const delta = plainMean === 0 ? 0 : sc.mean / plainMean - 1;
  lines.push(
    `| ${map.name} | ${Math.round(sp.p50)} | ${Math.round(sc.mean)} | ${Math.round(sc.p50)} | ${
      map.layout === undefined ? '—' : `${delta >= 0 ? '+' : ''}${pct(delta)}`
    } | ${pct(pass(c))} | ${pct(pass(p))} | ${bagged.toFixed(1)} | ${sc.secretsPerHunt.toFixed(2)} |`,
  );
  json.push({
    map: map.name,
    plinkerP50: sp.p50,
    competentMean: sc.mean,
    competentP50: sc.p50,
    competentPass: pass(c),
    plinkerPass: pass(p),
  });
}
const seconds = (performance.now() - started) / 1000;
lines.push('', `${seconds.toFixed(0)} s, ${workers} workers.`);
const text = lines.join('\n');
console.log(text);
if (out !== '') {
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, `${text}\n`);
  writeFileSync(
    out.replace(/\.md$/, '.json'),
    `${JSON.stringify({ biome, quota, seeds, maps: json }, null, 2)}\n`,
  );
}
