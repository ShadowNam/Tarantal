// v1.8b (D-062): fits each baboon frame's box to its drawing. Renders every frame alone (feet at a
// fixed origin), finds its opaque bounds and writes src/game/view/baboon/baboonBoxes.ts (each
// box: the bounds plus a margin, and the feet within it), so the sheet wastes no texture memory
// and nothing is clipped at a box edge. Run after changing the art:
//   npx tsx tools/art/baboonBoxes.ts
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { BABOON_FRAME_NAMES } from '../../src/game/view/baboon/baboonSheet';
import { opaqueBounds } from '../assets/image';
import { drawFrame, frameSeed } from './baboons';
import { renderSvg } from './raster';
import { g, svgDoc } from './svg';

/** Clear pixels round each drawing (design px). */
const MARGIN = 3;
const CANVAS = 520;
const ORIGIN: readonly [number, number] = [260, 380];

const lines: string[] = [];
for (const name of BABOON_FRAME_NAMES) {
  const svg = svgDoc(
    CANVAS,
    CANVAS,
    [0, 0, CANVAS, CANVAS],
    '',
    g({ transform: `translate(${ORIGIN[0]} ${ORIGIN[1]})` }, drawFrame(name, frameSeed(name))),
  );
  const b = opaqueBounds(renderSvg(svg));
  if (b === null) throw new Error(`${name}: empty`);
  if (b.x === 0 || b.y === 0 || b.x + b.w >= CANVAS || b.y + b.h >= CANVAS)
    throw new Error(`${name}: touches the measuring canvas`);
  const x0 = b.x - MARGIN;
  const y0 = b.y - MARGIN;
  const w = b.w + MARGIN * 2;
  const h = b.h + MARGIN * 2;
  lines.push(`  ${name}: { w: ${w}, h: ${h}, ox: ${ORIGIN[0] - x0}, oy: ${ORIGIN[1] - y0} },`);
}
const out = `// Generated by tools/art/baboonBoxes.ts (v1.8b, D-062): each baboon frame's box fitted to its
// drawing (design px at 1×) and the feet within it. Do not edit by hand.

export const BABOON_BOXES = {
${lines.join('\n')}
} as const;
`;
writeFileSync(join(process.cwd(), 'src/game/view/baboon/baboonBoxes.ts'), out);
console.log(`wrote ${lines.length} boxes`);
