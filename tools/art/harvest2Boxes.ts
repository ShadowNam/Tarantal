// v1.18 (D-081): fits each Phase 2 frame's box to its drawing (as tools/art/baboonBoxes.ts) and
// writes src/game/view/harvest/harvest2Boxes.ts. Run after changing the art:
//   npx tsx tools/art/harvest2Boxes.ts
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { HARVEST2_FRAME_NAMES } from '../../src/game/view/harvest/harvest2Sheet';
import { opaqueBounds } from '../assets/image';
import { drawFrame2, frameSeed2 } from './harvest2';
import { renderSvg } from './raster';
import { g, svgDoc } from './svg';

/** Clear pixels round each drawing (design px). */
const MARGIN = 3;
const CANVAS = 640;
const ORIGIN: readonly [number, number] = [320, 420];

const lines: string[] = [];
for (const name of HARVEST2_FRAME_NAMES) {
  const svg = svgDoc(
    CANVAS,
    CANVAS,
    [0, 0, CANVAS, CANVAS],
    '',
    g({ transform: `translate(${ORIGIN[0]} ${ORIGIN[1]})` }, drawFrame2(name, frameSeed2(name))),
  );
  const b = opaqueBounds(renderSvg(svg));
  if (b === null) throw new Error(`${name}: empty`);
  if (b.x === 0 || b.y === 0 || b.x + b.w >= CANVAS || b.y + b.h >= CANVAS)
    throw new Error(`${name}: touches the measuring canvas`);
  const x0 = b.x - MARGIN;
  const y0 = b.y - MARGIN;
  lines.push(
    `  ${name}: { w: ${b.w + MARGIN * 2}, h: ${b.h + MARGIN * 2}, ox: ${ORIGIN[0] - x0}, oy: ${ORIGIN[1] - y0} },`,
  );
}
const out = `// Generated by tools/art/harvest2Boxes.ts (v1.18, D-081): each Phase 2 frame's box fitted to its
// drawing (design px at 1×) and the feet within it. Do not edit by hand.

export const HARVEST2_BOXES = {
${lines.join('\n')}
} as const;
`;
writeFileSync(join(process.cwd(), 'src/game/view/harvest/harvest2Boxes.ts'), out);
console.log(`wrote ${lines.length} boxes`);
