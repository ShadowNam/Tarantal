// The PWA service worker (Tech §9, M5): generated at build time with the exact list of files the
// game needs, so the game loads offline after one visit. Pure functions (unit-tested) plus a
// small Vite plugin that writes dist/sw.js after the bundle is written.
import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import type { Plugin } from 'vite';
import { ASSET_INDEX_PATH, HD_INDEX_PATH } from '../src/game/assets/assetIndex';
import { readFullIndex } from './assets/fullIndex';
import { BUILD_MESSAGE, CACHE_PREFIX } from '../src/platform/swUpdate';
import { audioFiles, lazyAssetFiles } from './sizeBudget';

/** Files never precached (source maps, the worker itself, OS junk, Vite's build manifest). */
const SKIP = [/\.map$/, /^sw\.js$/, /(^|\/)\.DS_Store$/, /\.gitkeep$/, /^\.vite\//];

/**
 * Precache list (scope-relative URLs) from the built file paths (posix, relative to dist). M10:
 * delivered art and audio of the non-home biomes (`lazy`) are cached when first used instead,
 * so installing the PWA doesn't download every biome.
 */
export function precacheList(
  files: readonly string[],
  lazy: ReadonlySet<string> = new Set(),
): string[] {
  const keep = files.filter((f) => !SKIP.some((re) => re.test(f)) && !lazy.has(f));
  return ['./', ...[...new Set(keep)].sort()];
}

/** Cache version: a hash of the file list plus each file's content fingerprint. */
export function cacheVersion(entries: readonly (readonly [string, string])[]): string {
  const h = createHash('sha256');
  for (const [f, fp] of [...entries].sort(([a], [b]) => (a < b ? -1 : 1)))
    h.update(`${f}\n${fp}\n`);
  return h.digest('hex').slice(0, 16);
}

/**
 * The worker source. Navigations: network first (updates arrive), cached index.html when
 * offline (query strings ignored, so `/?seed=42` works offline too). v1.6 (D-042): the asset
 * index and any HTML are network first too (a stale index after a deploy names files the host no
 * longer has), cached copies only offline. Everything else: cache first, falling back to the
 * network and caching same-origin GETs that succeeded; a failed answer (404) goes to the page
 * as it is, never cached and never replaced by something else, so the loader can name it.
 * The worker names its build (`build`, swUpdate.buildIdOf) when a page asks, so a page offers a
 * reload only when it runs another build.
 */
export function serviceWorkerSource(
  version: string,
  precache: readonly string[],
  build = '',
): string {
  return `// Generated by tools/serviceWorker.ts — do not edit.
const CACHE = '${CACHE_PREFIX}${version}';
const BUILD = ${JSON.stringify(build)};
const PRECACHE = ${JSON.stringify(precache)};
const abs = (p) => new URL(p, self.registration.scope).href;

self.addEventListener('message', (event) => {
  if (event.data === ${JSON.stringify(BUILD_MESSAGE)} && event.ports[0]) event.ports[0].postMessage(BUILD);
});

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((c) => c.addAll(PRECACHE.map(abs)))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(keys.filter((k) => k.startsWith('${CACHE_PREFIX}') && k !== CACHE).map((k) => caches.delete(k))),
      )
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  // D-058: the Android test app's page and APK (tens of MB) are never cached by the game.
  if (url.pathname.includes('/android/')) return;
  if (req.mode === 'navigate') {
    event.respondWith(
      fetch(req).catch(() =>
        caches
          .match(abs('./index.html'), { ignoreSearch: true })
          .then((r) => r || caches.match(abs('./'), { ignoreSearch: true }))
          .then((r) => r || Response.error()),
      ),
    );
    return;
  }
  if (
    url.pathname.endsWith('/${ASSET_INDEX_PATH}') ||
    url.pathname.endsWith('/${HD_INDEX_PATH}') ||
    url.pathname.endsWith('.html')
  ) {
    event.respondWith(
      fetch(req)
        .then((res) => {
          if (res.ok && res.type === 'basic') {
            const copy = res.clone();
            caches.open(CACHE).then((c) => c.put(req, copy));
          }
          return res;
        })
        .catch(() =>
          caches.match(req, { ignoreSearch: true }).then((r) => r || Response.error()),
        ),
    );
    return;
  }
  event.respondWith(
    caches.match(req, { ignoreSearch: true }).then(
      (hit) =>
        hit ||
        fetch(req).then((res) => {
          if (res.ok && res.type === 'basic') {
            const copy = res.clone();
            caches.open(CACHE).then((c) => c.put(req, copy));
          }
          return res;
        }),
    ),
  );
});
`;
}

function listFiles(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? listFiles(path) : [path];
  });
}

/**
 * Vite plugin: after the build is written, writes dist/sw.js covering every file in dist. `build`
 * is the page's build id (swUpdate.buildIdOf of the build stamp's commit and time).
 */
export function serviceWorkerPlugin(build = ''): Plugin {
  let outDir = 'dist';
  return {
    name: 'tm-service-worker',
    apply: 'build',
    configResolved(config) {
      outDir = config.build.outDir;
    },
    closeBundle() {
      const files = listFiles(outDir).map((p) => relative(outDir, p).split(sep).join('/'));
      const indexPath = join(outDir, ASSET_INDEX_PATH);
      // Other biomes' files and every recording are cached on first use, not up front (a browser
      // plays one of each Ogg/MP3 pair).
      // D-053: with the HD half (HD files are cached when first used, never up front).
      const index = existsSync(indexPath) ? readFullIndex(outDir).index : null;
      const lazy = new Set([
        ...(index === null ? [] : lazyAssetFiles(index)),
        ...(index === null ? [] : audioFiles(index)),
      ]);
      const list = precacheList(files, lazy);
      const version = cacheVersion(
        list
          .filter((f) => f !== './')
          .map(
            (f) =>
              [
                f,
                createHash('sha1')
                  .update(readFileSync(join(outDir, f)))
                  .digest('hex'),
              ] as const,
          ),
      );
      writeFileSync(join(outDir, 'sw.js'), serviceWorkerSource(version, list, build));
    },
  };
}
