// daily seed and score submission. Pure TypeScript so it runs synchronously in Node and browsers.
import type { ContentBundle } from './schemas';

/**
 * Canonical JSON: object keys sorted, no whitespace, `$comment` keys dropped (comments are not
 * content). Arrays keep their order.
 */
export function canonicalJson(value: unknown): string {
  if (value === null || typeof value !== 'object') {
    if (typeof value === 'number' && !Number.isFinite(value)) {
      throw new Error('canonicalJson: non-finite number');
    }
    if (value === undefined || typeof value === 'function' || typeof value === 'symbol') {
      return 'null';
    }
    return JSON.stringify(value);
  }
  if (Array.isArray(value)) return `[${value.map(canonicalJson).join(',')}]`;
  const entries = Object.entries(value as Record<string, unknown>)
    .filter(([k, v]) => k !== '$comment' && v !== undefined)
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  return `{${entries.map(([k, v]) => `${JSON.stringify(k)}:${canonicalJson(v)}`).join(',')}}`;
}

